const OUTLOOK_FAMILY_PREFIX = 'The industry outlook for the near term is';
const OUTLOOK_LEADS = [];
const OUTLOOK_TAILS = [];
const COMPILED_OUTLOOK_LEADS = [];
const COMPILED_OUTLOOK_TAILS = [];

function _extractValues(tokenOrder, m) {
    const values = {};
    tokenOrder.forEach((capture, i) => {
        const rawCapture = m[i + 1] || '';
        if (typeof capture !== 'string') {
            if (capture.kind === 'choiceToken') {
                if (!rawCapture) return;
                const name = capture.name;
                let raw = rawCapture.trim();
                if (NORMALIZERS[name]) raw = NORMALIZERS[name](raw);
                (values[name] = values[name] || []).push(raw);
                return;
            }
            const normalized = rawCapture.trim().replace(/\s+/g, ' ');
            const selected = capture.matchers
                ? capture.matchers.findIndex((matcher) => matcher.test(normalized))
                : capture.alternatives.findIndex(
                    (value) => value.trim().replace(/\s+/g, ' ') === normalized
                );
            if (!values.__CHOICES) values.__CHOICES = [];
            values.__CHOICES[capture.choiceIndex] = selected;
            return;
        }
        const name = capture;
        let raw = rawCapture.trim();
        if (NORMALIZERS[name]) raw = NORMALIZERS[name](raw);
        (values[name] = values[name] || []).push(raw);
    });
    return values;
}

/**
 * Tries `t` against every known outlook lead, and — if the remainder after
 * a lead match is non-empty — against every known outlook tail. Each half
 * renders its OWN Korean independently from its OWN captured token values
 * (so e.g. two different @IND captures in lead vs. tail, if that ever
 * happened, wouldn't collide) and the two Korean strings are joined with a
 * space, matching how the translator writes lead+tail as two sentences.
 * An empty (or bare ".") remainder after the lead means an atomic,
 * tail-less sentence — just the lead's own Korean is returned.
 */
const OUTLOOK_MIDDLE = { source: '', korean: '' };

function matchOutlookSplit(t) {
    if (!t.startsWith(OUTLOOK_FAMILY_PREFIX)) return { matched: false };
    for (const lead of COMPILED_OUTLOOK_LEADS) {
        const leadMatch = lead.compiled.regex.exec(t);
        if (!leadMatch) continue;
        const rest = t.slice(leadMatch[0].length);
        const leadValues = _extractValues(lead.compiled.tokenOrder, leadMatch);
        const leadKo = renderKorean(lead.korean, leadValues);
        if (rest.trim() === '' || rest.trim() === '.') {
            return { matched: true, korean: leadKo, values: leadValues, source: lead.source };
        }
        if (rest.startsWith(OUTLOOK_MIDDLE.source)) {
            // OUTLOOK_TAILS entries are synced from the CSV with their
            // Source (EN) field's leading whitespace trimmed off (the runtime data
            // generator strips it before compileTailPattern sees it), so they no longer
            // carry the leading space that separated the old fused
            // "...while industry leader..." text. Trim it here to match.
            const afterMiddle = rest.slice(OUTLOOK_MIDDLE.source.length).replace(/^\s+/, '');
            for (const tail of COMPILED_OUTLOOK_TAILS) {
                const tailMatch = tail.compiled.regex.exec(afterMiddle);
                if (!tailMatch) continue;
                const tailValues = _extractValues(tail.compiled.tokenOrder, tailMatch);
                const tailKo = renderKorean(tail.korean, tailValues);
                return {
                    matched: true,
                    korean: leadKo + ' ' + OUTLOOK_MIDDLE.korean + ' ' + tailKo,
                    values: { ...leadValues, ...tailValues },
                    source: lead.source + OUTLOOK_MIDDLE.source + ' ' + tail.source,
                };
            }
        }
        for (const tail of COMPILED_OUTLOOK_TAILS) {
            const tailMatch = tail.compiled.regex.exec(rest);
            if (!tailMatch) continue;
            const tailValues = _extractValues(tail.compiled.tokenOrder, tailMatch);
            const tailKo = renderKorean(tail.korean, tailValues);
            return {
                matched: true,
                korean: leadKo + ' ' + tailKo,
                values: { ...leadValues, ...tailValues },
                source: lead.source + tail.source,
            };
        }
    }
    return { matched: false };
}

// A broad template whose source begins with @CORPFULL can otherwise swallow
// an entire wrapped outlook sentence and translate only its final clause.
// Keep the ordinary direct-template priority, but provide a narrowly scoped
// rescue for text that is unmistakably an outlook lead+tail composition.
function matchOutlookSplitWithWrapper(t) {
    const bare = matchOutlookSplit(t);
    if (bare.matched) return bare;

    const outlookPrefix = PREFIX_STRIP_RULES.find(
        ({ prefix }) => prefix === 'INDUSTRY OUTLOOK: '
    );
    if (outlookPrefix && t.startsWith(outlookPrefix.prefix)) {
        const inner = t.slice(outlookPrefix.prefix.length)
            .replace(OUTLOOK_LEAD_RE, OUTLOOK_FAMILY_PREFIX);
        const split = matchOutlookSplit(inner);
        if (split.matched) {
            return { ...split, korean: outlookPrefix.targetPrefix + split.korean };
        }
    }

    const possMatch = CORP_POSSESSIVE_OUTLOOK.exec(t);
    if (possMatch && outlookPrefix) {
        const rest = t.slice(possMatch[0].length);
        if (rest.startsWith(outlookPrefix.prefix)) {
            const inner = rest.slice(outlookPrefix.prefix.length)
                .replace(OUTLOOK_LEAD_RE, OUTLOOK_FAMILY_PREFIX);
            const split = matchOutlookSplit(inner);
            if (split.matched) {
                const companyKo = translateEntityValue('CORP', possMatch[1]);
                return {
                    ...split,
                    korean: LANG.possessive(companyKo, outlookPrefix.targetPrefix, split.korean),
                };
            }
        }
    }
    return { matched: false };
}

