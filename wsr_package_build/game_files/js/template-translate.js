// Case-insensitive; an unknown value falls back to the raw English so it
// never disappears from the sentence.
function translateEntityValue(tokenName, rawValue) {
    if (tokenName === 'DATE') return LANG.formatDate(rawValue);
    const record = lookupValueRecord(tokenName, rawValue);
    return record && record.target ? record.target : rawValue;
}

