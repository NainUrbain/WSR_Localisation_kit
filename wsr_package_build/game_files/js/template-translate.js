/**
 * Template-based translation for DYNAMIC (server-assembled) game text — the
 * sentence half of the localization runtime. dom-translate-hook.js replaces
 * text that exactly matches a fixed dictionary entry; everything the game
 * assembles from variables (company names, amounts, years ...) is matched
 * here against English source patterns instead.
 *
 * HOW IT WORKS (identical for every language):
 *   1. The active locale's data (game_files/js/locale/<prefix>-templates.json,
 *      generated from the locale's CSV files by pipeline_tools/runtime_data.py)
 *      supplies English source patterns with @TOKEN placeholders and their
 *      translations, fragment families, token value tables and entity names.
 *   2. Each source pattern is compiled once into a regex that pulls the
 *      variable VALUES back out of a real, already-assembled sentence.
 *   3. The translated template is rendered by substituting those values back
 *      in. Values are translated through the locale's tables, and everything
 *      grammar- or format-specific (particles, articles, dates, possessives)
 *      is delegated to the locale's language rules (lang-*.js).
 *
 * ADDING A LANGUAGE needs no change here: add a locale profile and CSVs, and
 * a rules module registered in locale_profiles.json if the language needs
 * its own grammar rules. locale-registry.js is generated by the pipeline.
 */

