function lookupValueRecord(tokenName, rawValue) {
    if (rawValue === undefined || rawValue === null) return null;
    const table = VALUE_TABLE_OF_TOKEN[tokenName];
    if (table) {
        const values = LOCALE_VALUES[table];
        return (values && values[String(rawValue).toUpperCase()]) || null;
    }
    return localeEntityRecord(tokenName, rawValue)
        || (TOKEN_ALIASES[tokenName] || []).map(name => localeEntityRecord(name, rawValue)).find(Boolean)
        || null;
}


