    const worldEconomySplit = matchWorldEconomyProseSplit(t);
    if (worldEconomySplit.matched) return worldEconomySplit;
    const direct = matchTemplateRaw(t);
    if (direct.matched) {
        // A real full outlook template should retain its existing direct-match
        // wording. Only replace a match claimed by some unrelated, broader
        // template (most notably a token-leading @CORPFULL tail template).
        if (!direct.source.startsWith(OUTLOOK_FAMILY_PREFIX)) {
            const outlookRescue = matchOutlookSplitWithWrapper(t);
            if (outlookRescue.matched) return outlookRescue;
        }
        return direct;
    }
