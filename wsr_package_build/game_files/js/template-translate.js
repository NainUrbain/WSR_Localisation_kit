// Normalize a captured raw value before it's substituted into the Korean
// template (strip currency signs / trailing % so the Korean template's own
// units — "백만 달러", "%" — aren't duplicated).
const NORMALIZERS = {
    AMOUNT: (v) => {
        const hasM = /\s*M\s*$/.test(v);
        const num = v.replace(/\s*M\s*$/, '').replace(/[$\s]/g, '').replace(/\.00$/, '');
        return hasM ? num + ' M.' : num;
    },
    SHARES: (v) => v.replace(/[$\s]/g, '').replace(/\.00$/, ''),
    // Accepts either "8%"/"8" or a spelled-out "eight percent" — reduces
    // either form down to a bare digit string.
    PCT: (v) => {
        const spelledMatch = /^([a-z\-]+)\s+percent$/i.exec(v.trim());
        if (spelledMatch && SPELLED_TO_NUM[spelledMatch[1].toLowerCase()] !== undefined) {
            return String(SPELLED_TO_NUM[spelledMatch[1].toLowerCase()]);
        }
        return v.replace(/%\s*$/, '');
    },
    QUARTERS: (v) => {
        const digitMatch = v.match(/\d+/);
        if (digitMatch) return digitMatch[0];
        const spelledMatch = /^([a-z\-]+)\s+quarters?$/i.exec(v.trim());
        if (spelledMatch && SPELLED_TO_NUM[spelledMatch[1].toLowerCase()] !== undefined) {
            return String(SPELLED_TO_NUM[spelledMatch[1].toLowerCase()]);
        }
        return v;
    },
    // "second" -> "2" (for "@QORD분기"), same idea as MONTH/MONTHS/YEARS
    // below.
    QORD: (v) => {
        const idx = ['first', 'second', 'third', 'fourth'].indexOf(v.trim().toLowerCase());
        return idx >= 0 ? String(idx + 1) : v;
    },
    // Month names are formatted by the active language (Korean uses digits).
    MONTH: (v) => LANG.month(v),
    // "three" -> "3" (or leaves a bare digit alone).
    MONTHS: (v) => {
        const key = v.trim().toLowerCase();
        return SPELLED_TO_NUM[key] !== undefined ? String(SPELLED_TO_NUM[key]) : v.trim();
    },
    // Same conversion as MONTHS, separate token name.
    YEARS: (v) => {
        const key = v.trim().toLowerCase();
        return SPELLED_TO_NUM[key] !== undefined ? String(SPELLED_TO_NUM[key]) : v.trim();
    },
    // Same conversion as MONTHS/YEARS, separate token name (see COUNT
    // TOKEN_PATTERNS comment above).
    COUNT: (v) => {
        const key = v.trim().toLowerCase();
        if (SPELLED_TO_NUM[key] !== undefined) return String(SPELLED_TO_NUM[key]);
        // A count is display text, not a value used in arithmetic. Preserve
        // the game's thousands separators ("1,800" stays "1,800") so order
        // confirmations remain readable in Korean.
        const trimmed = v.trim();
        if (/^\d+$/.test(trimmed)) {
            return trimmed.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
        }
        return trimmed;
    },
    RATIO: (v) => v.replace(/,/g, ''),
    // Dates and month/day pairs are formatted by the language rules.
    DATE: (v) => LANG.dateToken(v),
    MONTHDAY: (v) => LANG.monthDay(v),
};

function escapeRegex(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function flexWhitespace(escaped) {
    if (escaped.length > 0 && escaped.trim() === '') {
        // non-empty, pure-whitespace gap (typically directly between two
        // tokens, e.g. the " " in "@REGION @ASSET") -- keep strict,
        // at-least-one-space matching. An EMPTY segment (the leading gap
        // before the first token, or two tokens with literally nothing
        // between them) must stay optional/lenient here, or a template
        // starting with a token (no leading literal text at all) could
        // never match text with zero leading whitespace.
        return '\\s+';
    }
    return escaped.replace(/\s+/g, '\\s*');
}

// Inline literal choices use compact bracket syntax in CSV templates:
//   [the dominant company/industry leader]
//   [more/'']                         ('' means the word may be absent)
// The slash MUST touch both alternatives. This deliberately leaves existing
// literal UI text such as "[ Y / N ]" untouched.
function splitInlineChoice(inner) {
    const parts = [];
    let start = 0;
    let found = false;
    for (let i = 1; i < inner.length - 1; i++) {
        if (inner[i] !== '/') continue;
        if (/\s/.test(inner[i - 1]) || /\s/.test(inner[i + 1])) continue;
        parts.push(inner.slice(start, i).trim());
        start = i + 1;
        found = true;
    }
    if (!found) return null;
    parts.push(inner.slice(start).trim());
    return parts.map((part) => part === "''" ? '' : part);
}

// {a|b|c} — second choice syntax, pipe-delimited, no adjacency restriction
// needed ('|' isn't otherwise used in literal game text the way '/' is).
// '' means the option may be empty, same convention as [a/''].
function splitCurlyChoice(inner) {
    const parts = inner.split('|').map((part) => part.trim());
    if (parts.length < 2) return null;
    return parts.map((part) => part === "''" ? '' : part);
}

function compilePattern(sourcePattern, leadingWhitespace, anchoredAtEnd) {
    const partRe = /@([A-Z]+)\d*|\[([^\[\]\r\n]+)\]|\{([^{}\r\n]+)\}/g;
    let lastIndex = 0;
    let regexStr = leadingWhitespace ? '^\\s*' : '^';
    const tokenOrder = [];
    let relaxNextWhitespace = false;
    let choiceIndex = 0;
    let m;

    const appendLiteral = (literal) => {
        if (relaxNextWhitespace) {
            literal = literal.replace(/^\s+/, '');
            regexStr += '\\s*';
            relaxNextWhitespace = false;
        }
        regexStr += flexWhitespace(escapeRegex(literal));
    };

    while ((m = partRe.exec(sourcePattern))) {
        let bracketInner = m[2] !== undefined ? m[2] : m[3];
        let sourceChoiceIndex = choiceIndex;
        if (m[3] !== undefined) {
            const indexed = /^\[(\d+)\]([\s\S]+)$/.exec(bracketInner);
            if (indexed && Number(indexed[1]) >= 1) {
                sourceChoiceIndex = Number(indexed[1]) - 1;
                bracketInner = indexed[2];
            }
        }
        const alternatives = bracketInner === undefined ? null
            : (m[3] !== undefined ? splitCurlyChoice(bracketInner) : splitInlineChoice(bracketInner));
        if (bracketInner !== undefined && !alternatives) { partRe.lastIndex = m.index + 1; continue; }

        appendLiteral(sourcePattern.slice(lastIndex, m.index));
        // A trailing optional word may disappear immediately before '.',
        // so its preceding separator must disappear too ("asset {at|''}").
        if (alternatives?.includes('') && regexStr.endsWith('\\s+')) {
            regexStr = regexStr.slice(0, -3) + '\\s*';
        }
        if (m[1] !== undefined) {
            const tokenName = m[1];
            // Adjacent geography and asset tokens need a real dictionary
            // boundary: "overseas unit at a loss" is not a region name.
            const geographicAssetPrefix = ['LOCATION', 'REGION', 'COUNTRY'].includes(tokenName)
                && /^\s+@ASSET\d*/.test(sourcePattern.slice(partRe.lastIndex));
            const registered = geographicAssetPrefix
                ? [...(LOCALE_ENTITY_NAMES[tokenName] || [])].sort((a, b) => b.length - a.length)
                : [];
            const pattern = registered.length
                ? '(?:' + registered.map(escapeRegex).join('|') + ')(?=\\s)'
                : (TOKEN_PATTERNS[tokenName] || DEFAULT_TOKEN_PATTERN);
            regexStr += '(' + pattern + ')';
            tokenOrder.push(tokenName);
        } else {
            const followingTokenMatch = /^\s+@([A-Z]+)\d*/.exec(
                sourcePattern.slice(partRe.lastIndex)
            );
            const followingTokenName = followingTokenMatch?.[1] || null;
            const compiledAlternatives = alternatives.map((value, alternativeIndex) => {
                const tokenRe = /@([A-Z]+)\d*/g;
                const tokenCaptures = [];
                let pattern = '';
                let matcherPattern = '';
                let valueLastIndex = 0;
                let tokenMatch;
                while ((tokenMatch = tokenRe.exec(value))) {
                    const literal = value.slice(valueLastIndex, tokenMatch.index);
                    const tokenName = tokenMatch[1];
                    const tokenIsAlternativeTail = tokenRe.lastIndex === value.length;
                    // Optional geographic qualifiers are commonly followed
                    // directly by @ASSET ("Korean steel mill"). Two adjacent
                    // free-text tokens have no intrinsic boundary, so prefer
                    // registered entity names (longest first), then a single
                    // complete word. This prevents the permissive generic
                    // pattern from capturing only "Ko" or swallowing part of
                    // the asset. Registered multi-word names remain supported.
                    const geographicAssetPrefix = tokenIsAlternativeTail
                        && followingTokenName === 'ASSET'
                        && ['LOCATION', 'REGION', 'COUNTRY'].includes(tokenName);
                    const entityNames = geographicAssetPrefix
                        ? (LOCALE_ENTITY_NAMES[tokenName] || [])
                        : null;
                    const registeredEntityPattern = entityNames
                        ? [...entityNames]
                            .sort((a, b) => b.length - a.length)
                            .map((name) => flexWhitespace(escapeRegex(name)))
                            .join('|')
                        : '';
                    const tokenPattern = geographicAssetPrefix
                        ? (registeredEntityPattern
                            ? '(?:' + registeredEntityPattern + ')(?=\\s)'
                            : '[A-Za-z][A-Za-z.&\\-]*(?=\\s)')
                        : (TOKEN_PATTERNS[tokenName] || DEFAULT_TOKEN_PATTERN);
                    pattern += flexWhitespace(escapeRegex(literal));
                    matcherPattern += flexWhitespace(escapeRegex(literal));
                    pattern += '(' + tokenPattern + ')';
                    // The standalone choice value has no following space;
                    // the boundary lookahead belongs only in the full regex.
                    matcherPattern += '(?:' + (geographicAssetPrefix
                        ? tokenPattern.replace(/\(\?=\\s\)$/, '') : tokenPattern) + ')';
                    tokenCaptures.push({
                        kind: 'choiceToken',
                        name: tokenName,
                        choiceIndex: sourceChoiceIndex,
                        alternativeIndex,
                    });
                    valueLastIndex = tokenRe.lastIndex;
                }
                const tail = value.slice(valueLastIndex);
                pattern += flexWhitespace(escapeRegex(tail));
                matcherPattern += flexWhitespace(escapeRegex(tail));
                return {
                    pattern,
                    matcher: new RegExp('^' + matcherPattern + '$', 'i'),
                    tokenCaptures,
                };
            });
            const choicePattern = compiledAlternatives
                .map((alternative) => alternative.pattern)
                .join('|');
            regexStr += '(' + choicePattern + ')';
            tokenOrder.push({
                kind: 'choice',
                choiceIndex: sourceChoiceIndex,
                alternatives,
                matchers: compiledAlternatives.map((alternative) => alternative.matcher),
            });
            for (const alternative of compiledAlternatives) {
                tokenOrder.push(...alternative.tokenCaptures);
            }
            choiceIndex += 1;
            // In "[more/''] quickly", the space after the optional word
            // belongs to the present branch. When the word is absent the
            // same template must still match the normal single-space form.
            if (alternatives.includes('')) relaxNextWhitespace = true;
        }
        lastIndex = partRe.lastIndex;
    }
    appendLiteral(sourcePattern.slice(lastIndex));
    if (anchoredAtEnd) regexStr += '\\s*$';
    return { regex: new RegExp(regexStr, 'i'), tokenOrder };
}

function compileTemplate(sourcePattern) {
    return compilePattern(sourcePattern, true, true);
}

function compileLeadPattern(sourcePattern) {
    return compilePattern(sourcePattern, true, false);
}

// Mirror of compileLeadPattern() anchored at the END only (no leading
// '^\s*') -- used for OUTLOOK_TAILS below, matched against whatever text
// remains AFTER a lead has already matched a prefix of it.
function compileTailPattern(sourcePattern) {
    return compilePattern(sourcePattern, false, true);
}

