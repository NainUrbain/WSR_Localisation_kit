    // these lead + tail compositions only cover the remaining combinations.
    const subsidiarySplit = matchResearchSubsidiarySplit(t);
    if (subsidiarySplit.matched) return subsidiarySplit;
    const commoditySplit = matchAdvisoryCommoditySplit(t);
    if (commoditySplit.matched) return commoditySplit;
    const outlookSplit = matchOutlookSplit(t);
    if (outlookSplit.matched) return outlookSplit;
    const economicSplit = matchEconomicSplit(t);
    if (economicSplit.matched) return economicSplit;
    const turningAroundSplit = matchTurningAroundSplit(t);
    if (turningAroundSplit.matched) return turningAroundSplit;
    const industryGrowthSplit = matchIndustryGrowthSplit(t);
    if (industryGrowthSplit.matched) return industryGrowthSplit;
    const globalEconomySplit = matchGlobalEconomySplit(t);
