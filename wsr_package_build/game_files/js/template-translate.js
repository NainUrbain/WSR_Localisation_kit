function readLocaleTemplateData(locale) {
    if (!_fs || !_path || !locale) return null;
    const fileName = localeDataFile(locale, 'templates.json');
    if (!fileName) return null;
    const candidates = [
        _path.join(__dirname, 'locale', fileName),
        _path.join(__dirname, 'js', 'locale', fileName),
        _path.join(__dirname, '..', 'locale', fileName),
        _path.join(__dirname, '..', 'js', 'locale', fileName),
    ];
    for (const filePath of candidates) {
        try {
            if (!_fs.existsSync(filePath)) continue;
            return JSON.parse(_fs.readFileSync(filePath, 'utf8'));
        } catch (e) {
            console.error(`[template-translate] failed to load ${filePath}:`, e);
        }
    }
    return null;
}

/**
 * Make `locale` the active translation data set (no-op when it already is).
 * @returns {boolean} whether data for the locale exists
 */
export function activateLocale(locale) {
    if (locale === ACTIVE_TEMPLATE_LOCALE) return TEMPLATES.length > 0;
    const data = readLocaleTemplateData(locale);
    setRuntimeLocaleTemplates(locale, data);
    return !!data;
}

function syncActiveLocale() {
    const locale = localeManager.getCurrentLocale();
    if (locale !== ACTIVE_TEMPLATE_LOCALE) activateLocale(locale);
}

syncActiveLocale();
