// Suppress the ResizeObserver loop error. Translating text from our MutationObserver
// resizes elements, and React's ResizeObserver then reports notifications it could
// not deliver in the same frame. The warning is benign, but Electron raises it as an
// uncaught error, so only this error is swallowed (everything else passes through).
if (typeof window !== 'undefined') {
    window.addEventListener('error', (e) => {
        if (e.message && (
            e.message.includes('ResizeObserver loop completed') ||
            e.message.includes('ResizeObserver loop limit exceeded')
        )) {
            e.stopImmediatePropagation();
            e.preventDefault();
        }
    });
}

