function _keySuggestionWords(text){
  const stop=new Set(['a','an','and','are','as','at','be','by','click','for','from','has','in','is','it','of','on','or','the','this','to','until','with','you','your']);
  return String(text||'').replace(/@[A-Z][A-Z0-9_]*/g,' ').toLowerCase()
    .split(/[^a-z0-9]+/).filter(w=>w.length>1&&!stop.has(w));
}
function _keySuggestionSuffix(text){
  const words=_keySuggestionWords(text).slice(0,6);
  return words.map(w=>w.charAt(0).toUpperCase()+w.slice(1)).join('')||'Text';
}
function _keySuggestionFamily(key){
  const value=String(key||'').trim();
  if(!value||/^(?:CT|UI)-[0-9a-f]+$/i.test(value))return'';
  const first=value.indexOf('_');
  if(first<1)return'';
  const head=value.slice(0,first+1);
  // tutorial_Text_* is the one established two-part family in this data set.
  if(/^tutorial_Text_/i.test(value))return value.match(/^tutorial_Text_/i)[0];
  return head;
}
function _dynamicKeySuggestions(source,domText,oldKey){
  const basis=String(source||domText||'').trim();
  const suffix=_keySuggestionSuffix(basis);
  const query=new Set(_keySuggestionWords(basis));
  const familyScores=new Map();
  allRows.forEach(row=>{
    const family=_keySuggestionFamily(row.key);
    if(!family||row.key===oldKey)return;
    const words=new Set(_keySuggestionWords(row.en));
    let overlap=0;query.forEach(w=>{if(words.has(w))overlap++;});
    if(!overlap)return;
    const score=overlap*10-(Math.max(0,words.size-overlap)*0.25);
    const prev=familyScores.get(family);
    if(!prev||score>prev.score)familyScores.set(family,{score,key:row.key});
  });

  const semantic=[
    [/\btutorial\b/i,'tutorial_Text_'],
    [/\b(?:swap|notional)\b/i,'Swap_'],
    [/\b(?:futures?|commodity)\b/i,'Futures_'],
    [/\b(?:stock|shares?|securities)\b/i,'Stock_'],
    [/\b(?:loan|borrow|credit)\b/i,'Loan_'],
    [/\b(?:tax|taxable|income tax)\b/i,'Tax_'],
    [/\b(?:news|headline|announc(?:e|ed|ement))\b/i,'News_'],
    [/\b(?:report|financial|balance sheet|cash flow)\b/i,'FinancialUI_'],
    [/\b(?:confirm|confirmation|alert|warning)\b/i,'modal_']
  ];
  semantic.forEach(([re,family])=>{
    if(re.test(basis)&&!familyScores.has(family))familyScores.set(family,{score:6,key:'content category'});
  });
  const currentFamily=_keySuggestionFamily(oldKey);
  if(currentFamily&&!familyScores.has(currentFamily))familyScores.set(currentFamily,{score:5,key:'current key'});

  const used=new Set(allRows.map(r=>r.key));
  const seen=new Set();
  const makeUnique=base=>{
    if(!used.has(base)||base===oldKey)return base;
    let n=2;while(used.has(base+'_'+n))n++;
    return base+'_'+n;
  };
  const suggestions=[];
  Array.from(familyScores.entries()).sort((a,b)=>b[1].score-a[1].score).slice(0,5).forEach(([family,meta])=>{
    const value=makeUnique(family+suffix);
    if(seen.has(value))return;seen.add(value);
    const reason=meta.key==='content category'||meta.key==='current key'?meta.key:'similar to: '+meta.key;
    suggestions.push({value,label:value+'  ('+reason+')'});
  });
  const genericPrefix=/@[A-Z][A-Z0-9_]*/.test(basis)?'CT-':'UI-';
  const generic=makeUnique(_capGeneratedKey(basis,genericPrefix));
  if(!seen.has(generic))suggestions.push({value:generic,label:generic+'  (safe generated key)'});
  return suggestions;
}
function _renderedTemplateScore(rendered,template){
  const hay=_scanKeyMatchText(rendered);
  if(!hay||!template)return 0;
  const pieces=String(template).split(/@[A-Z][A-Z0-9_]*/g).map(piece=>{
    let value=_scanKeyMatchText(piece);
    for(const marker of ['은/는','이/가','을/를','과/와','로/으로','으로/로']){
      if(value.startsWith(marker)){value=value.slice(marker.length).trim();break;}
    }
    return value;
  }).filter(piece=>piece.length>=4);
  if(!pieces.length)return 0;
  let score=0,matched=0;
  pieces.forEach(piece=>{if(hay.includes(piece)){score+=piece.length;matched++;}});
  return matched===pieces.length?score+1000:score;
}
function _scanRowCsvMatch(row,rows){
  if(!row)return null;
  const direct=rows.find(r=>r.key===row.key);
  if(direct)return direct;
  const en=String(row.en||'').trim();
  if(en){const exact=rows.find(r=>String(r.en||'').trim()===en);if(exact)return exact;}
  const rendered=String(row.dom||'').trim();
  let best=null,bestScore=0;
  rows.forEach(candidate=>{
    const score=Math.max(
      _renderedTemplateScore(rendered,candidate.ko),
      _renderedTemplateScore(rendered,candidate.en)
    );
    if(score>bestScore){best=candidate;bestScore=score;}
  });
  return bestScore>=12?best:null;
}
