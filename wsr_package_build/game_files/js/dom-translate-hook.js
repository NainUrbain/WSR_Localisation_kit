function _parseTranslationCsvText(text) {
    text = String(text || '').replace(/^\uFEFF/, '');
    const records = [];
    let row = [], field = '', quoted = false;
    for (let i = 0; i < text.length; i++) {
        const ch = text[i];
        if (ch === '"') {
            if (quoted && text[i + 1] === '"') { field += '"'; i++; }
            else quoted = !quoted;
        } else if (ch === ',' && !quoted) {
            row.push(field); field = '';
        } else if ((ch === '\n' || ch === '\r') && !quoted) {
            if (ch === '\r' && text[i + 1] === '\n') i++;
            row.push(field); records.push(row); row = []; field = '';
        } else {
            field += ch;
        }
    }
    if (field || row.length) { row.push(field); records.push(row); }
    while (records.length && !records[0].some((v) => String(v || '').trim())) records.shift();
    if (!records.length) return [];
    const header = records.shift().map((v) => String(v || '').trim());
    const indexes = {};
    header.forEach((name, index) => { indexes[name] = index; });
    const targetColumn = header.find((name) => name.startsWith('Target (')) || 'Target (KO)';
    if (indexes.Key == null || indexes['Source (EN)'] == null || indexes[targetColumn] == null) {
        throw new Error('CSV requires Key, Source (EN), and a Target (...) header');
    }
    const localeData = loadLocaleData(localeManager.getCurrentLocale());
    return records.filter((values) => values.some((v) => String(v || '').trim())).map((values) => {
        const key = values[indexes.Key] || '';
        const en = values[indexes['Source (EN)']] || '';
        const stored = indexes.Category == null ? '' : (values[indexes.Category] || '').trim();
        return {
            key,
            category: stored || _classifyRow(key.trim(), en.trim(), localeData),
            en,
            ko: values[indexes[targetColumn]] || '',
        };
    });
}

// Same rule as pipeline_tools/translation_csvs.classify(): rows listed in
// key_structure.json (copied into the hook data's "structure") keep their
// category; otherwise a source with an @TOKEN / {choice}, several lines, or a
// quote key is a template and everything else is an exact-match label.
const _QUOTE_KEY_RE = /^(?:quotes_|event_quote)\d/i;
function _classifyRow(key, source, data) {
    const structured = data && data.structure && data.structure[key];
    if (structured) return structured;
    if (key.startsWith('label_')) return 'Label';
    if (key.startsWith('headerdef_')) return 'Header Glossary';
    if (/@[A-Z]|\{[^{}]*\}|\[[^\[\]]*\|/.test(source) || source.trim().includes('\n') || _QUOTE_KEY_RE.test(key)) {
        return 'Candidate Template';
    }
    return 'UI Label';
}

