function tryBareEntityWord(core) {
    // Master industry names legitimately contain '/', digits and hyphen
    // variants (CABLE/SATELLITE TV--U.S., RETAIL - - APPAREL, etc.).
    if (!/^[A-Za-z][A-Za-z0-9.&/' -]*$/.test(core)) return null;
    const industryMap = loadIndustryMap();
    const industryKey = normalizeIndustryKey(core);
    if (industryMap.has(industryKey)) return industryMap.get(industryKey);
    const countryMap = loadCountryMap();
    const countryKey = core.trim().toUpperCase();
    if (countryMap.has(countryKey)) return countryMap.get(countryKey);
    return null;
}
function escapeRegexLocal(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
// Returns { korean, consumedLen } if `node`'s own text is the first word of
// a known industry name continued in node.nextSibling, else null.
// `consumedLen` is how many characters of the SIBLING's text belong to the
// matched region name (dash + region words) — the caller trims exactly
// that many characters off the front of the sibling, leaving whatever
// comes after (" industry, but demand...") untouched and in place.
// The continuation text ("- NORTH AMERICA industry...") is almost never a
// sibling of the TEXT NODE itself — the text node's parent is usually an
// inline wrapper element (<a>/<span>) holding just that one word, so the
// continuation is really a sibling of the WRAPPER element, one level up.
// Check the text node's own nextSibling first (covers the case where
// there's no wrapper at all), then fall back to the parent element's
// nextSibling if this text node is its only/last child.
function findFragmentSibling(node) {
    if (node.nextSibling && node.nextSibling.nodeType === 3) return node.nextSibling;
    const parent = node.parentElement;
    if (parent && parent.lastChild === node && parent.nextSibling && parent.nextSibling.nodeType === 3) {
        return parent.nextSibling;
    }
    return null;
}

function tryIndustryFragment(node, core) {
    if (!/^[A-Z][A-Za-z.&]*$/.test(core)) return null; // a single bare capitalized word/token only
    const sib = findFragmentSibling(node);
    if (!sib || !sib.nodeValue) return null;
    const m = sib.nodeValue.match(/^(\s*--?\s*)([A-Z][A-Za-z\s]*)/);
    if (!m) return null;
    const afterDash = m[2];
    const words = afterDash.trim().split(/\s+/).filter(Boolean);
    if (words.length === 0) return null;
    const map = loadIndustryMap();
    // try the longest word-combination first (industry region names are at
    // most 2-3 words, e.g. "NORTH AMERICA"), so e.g. "AUTO -- NORTH AMERICA"
    // is preferred over a shorter, wrong partial match if one existed.
    for (let n = Math.min(3, words.length); n >= 1; n--) {
        const candidateWords = words.slice(0, n);
        const key = normalizeIndustryKey(core + ' -- ' + candidateWords.join(' '));
        if (map.has(key)) {
            const consumedRe = new RegExp('^\\s*--?\\s*' + candidateWords.map(escapeRegexLocal).join('\\s+'));
            const consumedMatch = sib.nodeValue.match(consumedRe);
            const consumedLen = consumedMatch ? consumedMatch[0].length : 0;
            return { korean: map.get(key), consumedLen };
        }
    }
    return null;
}

