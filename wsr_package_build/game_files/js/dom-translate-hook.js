function translateIfExactMatchCore(text) {
    const dict = currentDict();
    if (!dict) return null;
    const t = text.trim();
    if (!t) return null;
    const whole = lookupExactTranslation(t, dict);
    if (typeof whole === 'string' && whole && whole !== t) return whole;

    const sentences = splitIntoSentences(t);
    if (sentences.length < 2) return null; // nothing left to gain by splitting
    const translatedParts = [];
    let anyTranslated = false;
    for (const sentence of sentences) {
        if (isTargetScript(sentence)) {
            translatedParts.push(sentence);
            continue;
        }
        const part = lookupExactTranslation(sentence, dict);
        if (typeof part !== 'string' || !part || part === sentence) return null;
        translatedParts.push(part);
        anyTranslated = true;
    }
    if (!anyTranslated) return null; // no EN→KO translation happened at all
    return translatedParts.join(' ');
}

const UI_LABEL_PREFIX_STRIP_RULES = [
    { prefix: '<< ', koreanPrefix: '<< ' },
    { prefix: '>>', koreanPrefix: '>>  ' },
];

function translateIfExactMatch(text) {
    const direct = translateIfExactMatchCore(text);
    if (direct) return direct;
    const t = text.trim();
    for (const { prefix, koreanPrefix } of UI_LABEL_PREFIX_STRIP_RULES) {
        if (!t.startsWith(prefix)) continue;
        const rest = t.slice(prefix.length).replace(/^\s+/, '');
        if (!rest) continue;
        const inner = translateIfExactMatchCore(rest);
        if (inner) return koreanPrefix + inner;
    }
    return null;
}

function translateLabelsWithinText(text) {
    const info = currentLabelDict();
    if (!info || info.keys.length === 0) return null;
    let out = text;
    let any = false;
    for (const label of info.keys) {
        if (out.indexOf(label) === -1) continue;
        const translated = info.dict[label];
        if (typeof translated !== 'string' || !translated || translated === label) continue;
        const re = new RegExp(escapeRegexLocal(label) + '( {2,})?', 'g');
        const next = out.replace(re, (m, gap) => {
            if (!gap) return translated;
            const targetWidth = label.length + gap.length;
            const newGapWidth = Math.max(1, targetWidth - visualWidth(translated));
            return translated + ' '.repeat(newGapWidth);
        });
        if (next !== out) {
            out = next;
            any = true;
        }
    }
    // Long advisory/report lines often combine several independently captured
    // sentences. Those sentences live in the exact dictionary (not labels),
    // so whole-node exact matching cannot see them. Replace only long,
    // punctuation-bearing exact phrases to avoid touching short entity names
    // or numeric table cells, while allowing mixed English/Korean lines to be
    // completed in one pass.
    const exact = currentDict();
    if (exact) {
        const fragments = currentLongExactFragments();
        for (const { source, regex, anchor } of fragments) {
            if (anchor && out.indexOf(anchor) === -1) continue;
            const translated = exact[source];
            if (typeof translated !== 'string' || !translated || translated === source) continue;
            const next = out.replace(regex, translated);
            if (next !== out) {
                out = next; any = true;
                const key = currentKeyDict() && currentKeyDict()[source];
                if (key && typeof window !== 'undefined') {
                    if (!window.__WSR_SENT_KEY__) window.__WSR_SENT_KEY__ = new Map();
                    window.__WSR_SENT_KEY__.set(translated, key);
                }
            }
        }
    }
    return any ? out : null;
}

