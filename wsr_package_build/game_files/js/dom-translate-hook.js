function _applyTranslationRowsLive(rows) {
    const locale = localeManager.getCurrentLocale();
    if (!Array.isArray(rows)) return { labels: 0, templates: 0 };
    const folderLocale = _csvFolderLocale();
    if (folderLocale && folderLocale !== locale) return { labels: 0, templates: 0, skipped: folderLocale };
    const data = loadLocaleData(locale);
    if (!data) return { labels: 0, templates: 0 };
    let labels = 0, templates = 0;
    const updateTemplate = window.__WSR_UPDATE_RUNTIME_TEMPLATE__;
    for (const row of rows) {
        const source = String(row.en || '').trim();
        const korean = String(row.ko || '').trim();
        const key = String(row.key || '').trim();
        if (!source) continue;
        const category = String(row.category || '').trim() || _classifyRow(key, source, data);
        const isTemplate = category === 'Candidate Template';
        if (isTemplate) {
            if (typeof updateTemplate === 'function' && updateTemplate(source, korean, key)) templates++;
            continue;
        }
        if (category === 'Label') {
            // Substring labels keep their surrounding spaces (see runtime_data.py).
            const rawSource = String(row.en || '');
            if (korean) data.labels[rawSource] = String(row.ko || '');
            else delete data.labels[rawSource];
            sortedLabelKeysCache[locale] = Object.keys(data.labels).sort((a, b) => b.length - a.length);
            labels++;
            continue;
        }
        if (category && category !== 'UI Label' && category !== 'dialog') continue;
        if (korean) data.exact[source] = korean;
        else if (!key || data.keys[source] === key) delete data.exact[source];
        if (Object.prototype.hasOwnProperty.call(data.labels || {}, source)) {
            if (korean) data.labels[source] = korean;
            else delete data.labels[source];
        }
        if (key) data.keys[source] = key;
        labels++;
    }
    _keyLookupRevision++;
    if (typeof window.__WSR_TEMPLATE_APPLY_REFRESH__ === 'function') {
        window.__WSR_TEMPLATE_APPLY_REFRESH__();
    }
    restoreOriginalText();
    fullScan();
    tagParagraphContainers();
    return { labels, templates };
}

