const originalTextByNode = new Map(); // Text node -> original (pre-translation) nodeValue
const originalAttrsByEl = new Map();  // Element -> { attrName: original value, ... }

function stashOriginalText(node) {
    if (!originalTextByNode.has(node)) originalTextByNode.set(node, node.nodeValue);
}
function stashOriginalAttr(el, attr, value) {
    let rec = originalAttrsByEl.get(el);
    if (!rec) originalAttrsByEl.set(el, (rec = {}));
    if (!(attr in rec)) rec[attr] = value;
}
function pruneStashes() {
    for (const node of originalTextByNode.keys()) {
        if (!node.isConnected) originalTextByNode.delete(node);
    }
    for (const el of originalAttrsByEl.keys()) {
        if (!el.isConnected) originalAttrsByEl.delete(el);
    }
}
function restoreOriginalText() {
    for (const [node, original] of originalTextByNode) {
        if (node.isConnected) node.nodeValue = original;
    }
    originalTextByNode.clear();
    for (const [el, rec] of originalAttrsByEl) {
        if (el.isConnected) {
            for (const attr of Object.keys(rec)) el.setAttribute(attr, rec[attr]);
        }
    }
    originalAttrsByEl.clear();
}

