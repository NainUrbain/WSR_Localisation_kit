// Every locale's runtime data follows one naming scheme, generated by the
// pipeline: locale/<prefix>-hook-data.json (e.g. ko-hook-data.json for
// ko-KR). It holds BOTH matching strategies as separate top-level keys — kept
// separate so the two can never be confused (see file header, "SECOND
// PASS": a full-sentence "exact" entry must never accidentally get applied
// as a substring inside an unrelated paragraph).
//   { "exact": { "English text": "translation", ... },
//     "labels": { "SHORT LABEL:": "translation:", ... } }
// A locale without data (the game's own English) is left untouched.
function localeFile(locale, suffix) {
    return localeDataFile(locale, suffix);
}
const missingLocaleData = new Set(); // locales whose hook data file does not exist

const loadedData = {};           // locale -> {exact, labels}, lazy-loaded + cached
const sortedLabelKeysCache = {}; // locale -> label keys sorted longest-first

// __dirname doesn't reliably point at this file's own folder (js/) —
// depending on how this app bundles/serves its renderer JS, __dirname
// can resolve to the app root (resources/app) instead of resources/app/js.
// Try every plausible location instead of hardcoding one.
function jsonCandidates(fileName) {
    return [
        path.join(__dirname, 'locale', fileName),
        path.join(__dirname, 'js', 'locale', fileName),
        path.join(__dirname, '..', 'locale', fileName),
        path.join(__dirname, '..', 'js', 'locale', fileName),
    ];
}
function findJsonNear(fileName) {
    if (!fs || !path || !fileName) return null;
    return jsonCandidates(fileName).find((p) => { try { return fs.existsSync(p); } catch (_) { return false; } }) || null;
}

function readJsonNear(fileName) {
    const candidates = [
        path.join(__dirname, 'locale', fileName),           // __dirname == .../js
        path.join(__dirname, 'js', 'locale', fileName),      // __dirname == .../app (root)
        path.join(__dirname, '..', 'locale', fileName),      // __dirname one level too deep
        path.join(__dirname, '..', 'js', 'locale', fileName),
    ];
    let loaded = null;
    let lastErr = null;
    for (const filePath of candidates) {
        try {
            if (!fs.existsSync(filePath)) continue;
            const raw = fs.readFileSync(filePath, 'utf8');
            loaded = JSON.parse(raw);
            console.log(`[dom-translate-hook] loaded ${fileName} from ${filePath}`);
            break;
        } catch (e) {
            lastErr = e;
        }
    }
    if (!loaded) {
        console.error(`[dom-translate-hook] failed to load ${fileName} — tried:`, candidates, lastErr || '');
        loaded = {};
    }
    return loaded;
}

function loadLocaleData(locale) {
    const fileName = localeFile(locale, 'hook-data.json');
    if (!fileName || !fs || !path || missingLocaleData.has(locale)) return null;
    if (loadedData[locale]) {
        if (typeof window !== 'undefined') window.__WSR_LOCALE_HOOK_DATA__ = loadedData[locale];
        return loadedData[locale];
    }
    if (!findJsonNear(fileName)) {
        missingLocaleData.add(locale);
        return null;
    }
    const raw = readJsonNear(fileName);
    const data = {
        exact: raw.exact || {},
        labels: raw.labels || {},
        keys: raw.keys || {},
        structure: raw.structure || {},
    };
    loadedData[locale] = data;
    if (typeof window !== 'undefined') window.__WSR_LOCALE_HOOK_DATA__ = data;
    // Longest-key-first so e.g. a label that's a prefix of a longer label
    // (none currently, but future-proof) doesn't shadow the longer match.
    sortedLabelKeysCache[locale] = Object.keys(data.labels).sort((a, b) => b.length - a.length);
    return data;
}

function loadDictionary(locale) {
    const data = loadLocaleData(locale);
    return data ? data.exact : null;
}

function loadLabelDictionary(locale) {
    const data = loadLocaleData(locale);
    return data ? data.labels : null;
}

