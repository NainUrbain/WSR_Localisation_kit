let headerLinesCache = null;
let headerLinesLocale = null;
function loadHeaderLines() {
    const locale = localeManager.getCurrentLocale();
    if (headerLinesCache && headerLinesLocale === locale) return headerLinesCache;
    headerLinesLocale = locale;
    // Header-line tagging is language-neutral: one shared file for every locale.
    const fileName = 'header-lines.json';
    if (!loadLocaleData(locale) || !findJsonNear(fileName)) return (headerLinesCache = {});
    const raw = readJsonNear(fileName);
    headerLinesCache = (raw && typeof raw === 'object' && !Array.isArray(raw)) ? raw : {};
    for (const [k, v] of Object.entries(headerLinesCache)) {
        const tk = k.trim();
        if (tk !== k && !(tk in headerLinesCache)) headerLinesCache[tk] = String(v).trim();
    }
    return headerLinesCache;
}

// Wraps every known header phrase found in `text` as "[!<phrase>]" (longest
// terms first, so e.g. "TYPE OF FUTURES" is tagged whole rather than its
// substring "TYPE OF OPTION" — no actual overlap today, but future-proof
// the same way loadLocaleData()'s longest-key-first label sort already is).
// Returns the tagged string, or null if no known header phrase was found
// (so the caller can tell "nothing to do" apart from "no-op tag insert").
function tagKnownHeaderTerms(text) {
    if (!loadLocaleData(localeManager.getCurrentLocale())) return null;
    const terms = loadHeaderTerms();
    if (!terms.length) return null;
    let out = text;
    let any = false;
    for (const term of terms) {
        if (out.indexOf(term) === -1) continue;
        // Word-boundary-free plain substring replace -- these are fixed,
        // fully-uppercase report-generator strings (not natural prose), so
        // there's no risk of an accidental partial-word match the way a
        // dictionary word inside free-form text might have.
        out = out.split(term).join(`[!${term}]`);
        any = true;
    }
    return any ? out : null;
}

let longExactFragmentsData = null;
let longExactFragmentsRevision = -1;
let longExactFragmentsCache = [];
function currentLongExactFragments() {
    const exact = currentDict();
    if (!exact) return [];
    if (longExactFragmentsData === exact && longExactFragmentsRevision === _keyLookupRevision) {
        return longExactFragmentsCache;
    }
    longExactFragmentsData = exact;
    longExactFragmentsRevision = _keyLookupRevision;
    longExactFragmentsCache = Object.keys(exact)
        .filter((source) => source.length >= 20 && /[.!?)]$/.test(source) && !source.includes('@'))
        .sort((a, b) => b.length - a.length)
        .map((source) => ({
            source,
            // Fixed-width report renderers can insert newlines or runs of
            // padding spaces inside an otherwise exact sentence. Match the
            // authored words/punctuation exactly while treating whitespace
            // boundaries as layout, not content.
            regex: new RegExp(source.trim().split(/\s+/).map(escapeRegexLocal).join('\\s+'), 'g'),
            anchor: source.trim().split(/\s+/).reduce((a, b) => (b.length > a.length ? b : a), ''),
        }));
    return longExactFragmentsCache;
}

