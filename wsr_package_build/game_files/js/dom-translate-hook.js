        var dir = dirOf(p), map = prefixMap(dir), names = allFileNames(map);
        var recs = records(String(text).replace(/^﻿/, ''));
        if (!recs.length) throw new Error('empty CSV text');
        var canonicalHeader = fieldsOf(recs.shift()).map(function (name) { return String(name || '').trim(); });
